
// Pre Increment
let a = 10;
let b = ++a; // (increment the a by 1)

// Pre increment -> ++a ->. increase the value and then assign.
console.log(b);
console.log(a);

// Decreement
let a1 = 10;
let b1 = --a1; // (decrement the a by 1)
// decrease the value and then assign.
console.log(b1); // 9
console.log(a1);  // 9


let a2 = 10;
let b2 = a2--; // (decrement the a by 1)
// first assign and then decrement
console.log(b2);  // 10
console.log(a2);  // 9