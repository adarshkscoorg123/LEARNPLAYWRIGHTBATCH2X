
let arr = [1, 2, 3];
console.log(arr);

// Push function Adds value to  the END of the array.
arr.push(4);
console.log(arr);


// Remove the value from the END of the array.
arr.pop();
console.log(arr);

// We can push multiple elements also
arr.push(5, 6);
console.log(arr);

arr.pop();
console.log(arr);

// Adds the value(20) to the BEGINNING of an array
arr.unshift(20);
console.log(arr);


// Removes the value from BEGINNING of any array
arr.shift();
console.log(arr); // removes 20 from array

arr.shift();
console.log(arr); // removes 1 from array
console.log("-------------");

